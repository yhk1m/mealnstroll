// 60갑자 (가짜 일진용) — 날짜를 60으로 모듈로 연산해서 인덱싱.
const STEMS = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'];
const BRANCHES = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];
const KOREAN_STEMS = ['갑', '을', '병', '정', '무', '기', '경', '신', '임', '계'];
const KOREAN_BRANCHES = ['자', '축', '인', '묘', '진', '사', '오', '미', '신', '유', '술', '해'];

export function fakeIljin(date) {
  const epoch = new Date(2026, 0, 1).getTime();
  const d = Math.floor((date.getTime() - epoch) / 86400000);
  const idx = ((d % 60) + 60) % 60;
  const stemIdx = idx % 10;
  const branchIdx = idx % 12;
  return {
    hanja: `${STEMS[stemIdx]}${BRANCHES[branchIdx]}日`,
    korean: `${KOREAN_STEMS[stemIdx]}${KOREAN_BRANCHES[branchIdx]}일`
  };
}
